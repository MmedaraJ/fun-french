// Emoji are drawn with Twemoji SVGs (CC-BY 4.0) copied to /vendor/twemoji at build time,
// so pictures look the same on every device and work offline.

function codepoints(str: string): string[] {
  return [...str].map((c) => c.codePointAt(0)!.toString(16));
}

/** Twemoji file name: keep FE0F only inside ZWJ sequences. */
export function twemojiFile(emoji: string): string {
  const s = emoji.includes('‍') ? emoji : emoji.replace(/️/g, '');
  return codepoints(s).join('-');
}

export function twemojiUrl(emoji: string): string {
  return `${import.meta.env.BASE_URL}vendor/twemoji/${twemojiFile(emoji)}.svg`;
}

/** Fallback name without any FE0F (a few ZWJ files are stored that way). */
export function twemojiUrlAlt(emoji: string): string {
  return `${import.meta.env.BASE_URL}vendor/twemoji/${codepoints(emoji.replace(/️/g, '')).join('-')}.svg`;
}

export function isSingleEmoji(s: string): boolean {
  const t = s.trim();
  if (!t) return false;
  try {
    const seg = new Intl.Segmenter(undefined, { granularity: 'grapheme' });
    const parts = [...seg.segment(t)];
    return parts.length === 1 && /\p{Extended_Pictographic}|\p{Regional_Indicator}|⃣/u.test(t);
  } catch {
    return /\p{Extended_Pictographic}/u.test(t) && t.length <= 11;
  }
}

/** First emoji grapheme in a string, if any. */
export function firstEmoji(s: string): string | undefined {
  try {
    const seg = new Intl.Segmenter(undefined, { granularity: 'grapheme' });
    for (const { segment } of seg.segment(s)) {
      if (/\p{Extended_Pictographic}|⃣/u.test(segment)) return segment;
    }
  } catch {
    const m = s.match(/\p{Extended_Pictographic}(‍\p{Extended_Pictographic}|️)*/u);
    return m?.[0];
  }
  return undefined;
}

export interface EmojiEntry {
  e: string;
  name: string;
  group: string;
  keywords: string[];
}

let indexPromise: Promise<EmojiEntry[]> | null = null;

/** Lazily loads the emoji search index generated by scripts/prepare-assets.mjs. */
export function loadEmojiIndex(): Promise<EmojiEntry[]> {
  if (!indexPromise) {
    indexPromise = import('../generated/emoji-data.json').then((mod) => {
      const data = (mod.default ?? mod) as { groups: string[]; rows: [string, string, number, string][] };
      return data.rows.map(([e, name, gi, kw]) => ({
        e,
        name,
        group: data.groups[gi],
        keywords: kw ? kw.split('|') : [],
      }));
    });
  }
  return indexPromise;
}

const STOP = new Set(['the', 'a', 'an', 'to', 'of', 'and', 'my', 'your', 'some', 'is', 'in', 'on', 'for', 'with']);

function stem(w: string): string {
  return w.replace(/(ies)$/, 'y').replace(/(es|s)$/, '');
}

/** Rank emoji for a free-text query such as an English translation ("the red apple"). */
export function searchEmoji(index: EmojiEntry[], query: string, limit = 24): EmojiEntry[] {
  const words = query
    .toLowerCase()
    .replace(/[^a-z0-9 ]/g, ' ')
    .split(/\s+/)
    .filter((w) => w && !STOP.has(w));
  if (!words.length) return [];
  const scored: { entry: EmojiEntry; score: number }[] = [];
  for (const entry of index) {
    const name = entry.name.toLowerCase();
    const nameWords = name.split(/[\s:,-]+/);
    let score = 0;
    for (const w of words) {
      const sw = stem(w);
      if (name === w) score += 100;
      else if (nameWords.includes(w) || nameWords.includes(sw)) score += 40 - Math.min(nameWords.length, 10);
      else if (entry.keywords.includes(w) || entry.keywords.includes(sw)) score += 18;
      else if (w.length >= 4 && (name.includes(sw) || entry.keywords.some((k) => k.startsWith(sw)))) score += 6;
    }
    if (score > 0) {
      if (entry.group === 'Flags') score -= 15;
      scored.push({ entry, score });
    }
  }
  scored.sort((a, b) => b.score - a.score);
  return scored.slice(0, limit).map((s) => s.entry);
}
